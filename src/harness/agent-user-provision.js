'use strict';

/**
 * Agent user provisioning — 最小权限代理执行初始化脚本生成器。
 *
 * 目标：创建普通用户（默认 oneshell-agent），加入日志读取组，并配置只读 sudo 白名单。
 * 注意：这是显式初始化动作，不会在执行命令时偷偷创建用户；个人项目需要保留关闭/直通开关。
 */

const DEFAULT_AGENT_USER = 'oneshell-agent';

function cleanUser(value) {
  const text = String(value || '').trim();
  if (!/^[a-z_][a-z0-9_-]{0,31}$/i.test(text)) return '';
  return text;
}

function shellQuote(value) {
  return `'${String(value).replace(/'/g, `'\\''`)}'`;
}

function buildAgentUserProvisionScript({ agentUser = DEFAULT_AGENT_USER } = {}) {
  const user = cleanUser(agentUser) || DEFAULT_AGENT_USER;
  const quotedUser = shellQuote(user);
  const sudoersPath = `/etc/sudoers.d/${user}-readonly`;
  const quotedSudoersPath = shellQuote(sudoersPath);

  return `
set -eu
AGENT_USER=${quotedUser}
SUDOERS_PATH=${quotedSudoersPath}

if [ "$(id -u 2>/dev/null || echo 1)" != "0" ]; then
  echo "ERROR: 初始化 Agent 普通用户需要 root 权限" >&2
  exit 1
fi

if ! id "$AGENT_USER" >/dev/null 2>&1; then
  if command -v useradd >/dev/null 2>&1; then
    useradd -m -s /bin/bash "$AGENT_USER"
  elif command -v adduser >/dev/null 2>&1; then
    adduser --disabled-password --gecos '' "$AGENT_USER"
  else
    echo "ERROR: 未找到 useradd/adduser，无法创建用户" >&2
    exit 1
  fi
fi

for group in adm systemd-journal; do
  if getent group "$group" >/dev/null 2>&1; then
    usermod -aG "$group" "$AGENT_USER" 2>/dev/null || true
  fi
done

tmp_file=$(mktemp)
{
  echo "# Generated by 1Shell. Read-only sudo whitelist for AI perception commands."
  echo "Defaults:$AGENT_USER !requiretty"
  emit_cmd() {
    command_path=$(command -v "$1" 2>/dev/null || true)
    shift || true
    if [ -n "$command_path" ]; then
      if [ "$#" -eq 0 ]; then
        echo "$AGENT_USER ALL=(root) NOPASSWD: $command_path *"
      else
        for pattern in "$@"; do
          echo "$AGENT_USER ALL=(root) NOPASSWD: $command_path $pattern"
        done
      fi
    fi
  }
  emit_cmd journalctl '*'
  emit_cmd ss '*'
  emit_cmd lsof '*'
  emit_cmd ps '*'
  emit_cmd df '*'
  emit_cmd du '*'
  emit_cmd ip '*'
  emit_cmd uname '*'
  emit_cmd hostname '*'
  emit_cmd systemctl 'status *' 'show *' 'list-units *' 'list-unit-files *' 'list-timers *' 'is-active *' 'is-enabled *' 'is-failed *' 'cat *' 'get-default *'
} > "$tmp_file"

chmod 0440 "$tmp_file"
if command -v visudo >/dev/null 2>&1; then
  visudo -cf "$tmp_file" >/dev/null
fi
install -m 0440 "$tmp_file" "$SUDOERS_PATH"
rm -f "$tmp_file"

printf 'AGENT_USER=%s\n' "$AGENT_USER"
printf 'SUDOERS_PATH=%s\n' "$SUDOERS_PATH"
printf 'INIT_OK=1\n'
`.trim();
}

function buildReadonlySudoProbeCommand({ agentUser = DEFAULT_AGENT_USER } = {}) {
  const user = cleanUser(agentUser) || DEFAULT_AGENT_USER;
  const quotedUser = shellQuote(user);
  return `runuser -u ${user} -- bash -lc ${shellQuote('id && sudo -n true 2>/dev/null || true; sudo -n journalctl --version >/dev/null 2>&1 && echo READONLY_SUDO_OK=1 || echo READONLY_SUDO_OK=0')}`;
}

module.exports = {
  DEFAULT_AGENT_USER,
  cleanUser,
  shellQuote,
  buildAgentUserProvisionScript,
  buildReadonlySudoProbeCommand,
};
